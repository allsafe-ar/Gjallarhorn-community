/** Mensaje de error del backend en el idioma activo; si no se conoce, va tal cual. */
export function traducirError(msg: string): string {
  const i = idiomaActual()
  if (i === 'es' || !msg) return msg
  const fijo = ERRORES[msg]
  if (fijo) return fijo[i]
  for (const p of ERRORES_PATRON) { const m = p.re.exec(msg); if (m) return p[i](m) }
  return msg
}
