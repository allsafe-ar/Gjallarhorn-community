/** Devuelve la taxonomía con los nombres en el idioma pedido. Lo que no esté traducido queda como vino. */
export function localizarTaxonomia(tx: Taxonomia | undefined, idioma: Idioma): Taxonomia | undefined {
  if (!tx || idioma === 'es') return tx
  const d = TAX[idioma]
  const mapa = (o: Record<string, string>, tr: Record<string, string>) =>
    Object.fromEntries(Object.entries(o).map(([k, v]) => [k, tr[k] ?? v]))
  return {
    ...tx,
    categorias: Object.fromEntries(Object.entries(tx.categorias).map(([k, c]) => [k, {
      nombre: d.categorias[k] ?? c.nombre, tipos: mapa(c.tipos, d.tipos),
    }])),
    estados: mapa(tx.estados, d.estados),
    disposicion: mapa(tx.disposicion, d.disposicion),
    vencimientos: mapa(tx.vencimientos, d.vencimientos),
  }
}

/** Nota de coincidencia guardada por el backend ("número de serie", "dirección IP (pero difiere serie)"). */
export function traducirCriterio(criterio: string, t: Textos): string {
  let r = criterio
  for (const [es, otro] of Object.entries(t.criterios)) r = r.split(es).join(otro)
  return r
}

